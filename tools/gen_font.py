"""gen_font.py — 生成 16×16 中文字体 C 头文件

从 GB2312 字符集 + ASCII 渲染位图字体，输出 firmware/main/font_cjk.h
用法: .venv/Scripts/python tools/gen_font.py > firmware/main/font_cjk.h
"""

import sys
from PIL import Image, ImageFont, ImageDraw

# ── 配置 ──
FONT_PATH = "C:/Windows/Fonts/simsun.ttc"  # 宋体，小字号嵌入点阵
FONT_SIZE = 14  # SimSun 14px 正好对应 16×16 点阵字符

# ── 收集字符集 ──

chars = []

# 1. ASCII 可打印字符
for c in range(0x20, 0x7F):
    chars.append(chr(c))

# 2. 常用中文标点
extra_punct = (
    "　、。·×—‘’“”"
    "…《》『』【】！（）"
    "，：；？～ –―‖•"
    "′″℃Ⅰ←↑→↓"
    "─│└┘├┤┬┴┼"
    "○◎●★☆♀♂"
    "©®™°"
    "＂＃＄％＆＇）＊＋"
    "－．／０１２３４５"
    "６７８９：；＜＝＞"
    "？＠ＡＢＣＤＥＦＧ"
    "ＨＩＪＫＬＭＮＯＰ"
    "ＱＲＳＴＵＶＷＸＹ"
    "Ｚ［＼］＾＿｀ａｂ"
    "ｃｄｅｆｇｈｉｊｋ"
    "ｌｍｎｏｐｑｒｓｔ"
    "ｕｖｗｘｙｚ｛｜｝"
)
for ch in extra_punct:
    if ch not in chars:
        chars.append(ch)

# 3. GB2312 全部汉字 (6763 字)
gb_chars = set()
for hi in range(0xA1, 0xF8):
    for lo in range(0xA1, 0xFF):
        try:
            ch = bytes([hi, lo]).decode("gb2312")
            gb_chars.add(ch)
        except (UnicodeDecodeError, LookupError):
            pass
# 去重后排序
gb_sorted = sorted(gb_chars - set(chars))
chars.extend(gb_sorted)

# ── 渲染位图 ──

# 进度信息不输出（避免污染头文件）

font = ImageFont.truetype(FONT_PATH, FONT_SIZE, encoding="unic")

glyphs = []     # list of bytes(32)
lookup = []     # list of (codepoint, index)

for i, ch in enumerate(chars):
    # 创建 16×16 单色画布
    img = Image.new("1", (16, 16), 0)
    draw = ImageDraw.Draw(img)
    # 居中绘制 (SimSun 14px 在 16×16 框内自然居中)
    draw.text((0, -1), ch, font=font, fill=1)

    data = bytearray(32)
    for y in range(16):
        row = 0
        for x in range(16):
            if img.getpixel((x, y)):
                row |= 0x8000 >> x
        data[y * 2] = (row >> 8) & 0xFF
        data[y * 2 + 1] = row & 0xFF

    glyphs.append(data)
    lookup.append((ord(ch), i))

    if (i + 1) % 1000 == 0:
        print(f"  ... {i+1}/{len(chars)}", file=sys.stderr, flush=True)

# ── 输出 C 头文件 ──

header = f"""#pragma once
/** 16×16 CJK bitmap font — auto-generated by tools/gen_font.py
 *  {len(glyphs)} glyphs, {len(glyphs)*32} bytes bitmap data
 *
 *  字体: SimSun 宋体 14px → 16×16 点阵
 *  覆盖: ASCII + 中文标点 + GB2312 ({len(gb_sorted)} 汉字)
 */
#include <stdint.h>

#define FONT_CJK_COUNT {len(glyphs)}
#define FONT_CJK_BYTES {len(glyphs)*32}

/* 16×16 位图, 每字符 32 字节 (16 行 × 2 字节/行, MSB-left, row-major) */
static const uint8_t _cjk_bitmap[{len(glyphs)}][32] = {{
"""

for g in glyphs:
    hex_bytes = ", ".join(f"0x{b:02X}" for b in g)
    header += f"    {{{hex_bytes}}},\n"

header += "};\n\n"

header += f"""/* Unicode code point → glyph index, sorted for binary search */
static const struct {{ uint32_t cp; uint16_t idx; }} _cjk_lookup[{len(lookup)}] = {{
"""

for cp, idx in lookup:
    header += f"    {{0x{cp:04X}, {idx}}},\n"

header += "};\n\n"

header += """/** 二分查找 Unicode code point → glyph 位图 (返回 NULL 表示无此字) */
static inline const uint8_t *font_cjk_lookup(uint32_t codepoint) {
    int lo = 0, hi = FONT_CJK_COUNT - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        uint32_t cp = _cjk_lookup[mid].cp;
        if (cp == codepoint) return _cjk_bitmap[_cjk_lookup[mid].idx];
        if (cp < codepoint) lo = mid + 1;
        else hi = mid - 1;
    }
    return NULL;
}
"""

print(header)
print(f"\n// Generated {len(glyphs)} glyphs, {len(glyphs)*32} bytes bitmap data", file=sys.stderr)
